const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, he };

function initialLocale(): Locale {
  return navigator.language.toLowerCase().startsWith("he") ? "he" : "en";
}

export function useI18n() {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);
  const direction = locale === "he" ? "rtl" : "ltr";
  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = direction;
  }, [direction, locale]);
  const t = (key: TranslationKey, values: Record<string, string | number> = {}) => {
    let translated = dictionaries[locale][key];
    for (const [name, value] of Object.entries(values)) translated = translated.replaceAll(`{${name}}`, String(value));
    return translated;
  };
  const status = (value: string) => {
    const key = `status.${value}` as TranslationKey;
    return dictionaries[locale][key] ?? value;
  };
  const errorText = (value: string) => {
    const key = `error.${value}` as TranslationKey;
    return dictionaries[locale][key] ?? dictionaries[locale]["error.generic"];
  };
  const setLocale = (value: Locale) => setLocaleState(value);
  return { locale, direction, setLocale, status, errorText, t };
}
